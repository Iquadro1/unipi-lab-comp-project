import numpy as np
import matplotlib.pyplot as plt
from mpl_toolkits.mplot3d import Axes3D # Required for 3D plotting

def generate_isosphere(subdivisions: int = 3, radius: float = 1.0):
    """
    Generates a point cloud for a sphere using icosahedron subdivision.

    This method starts with an icosahedron and recursively subdivides its
    triangular faces into smaller triangles, projecting the new vertices
    onto the sphere. This results in a highly uniform point distribution.

    Args:
        subdivisions (int): The number of times to recursively subdivide.
                            0 results in a 12-vertex icosahedron.
                            3-4 provides a good sphere-like appearance.
        radius (float): The desired radius of the sphere.

    Returns:
        np.ndarray: A numpy array of shape (N, 3) containing the xyz coordinates
                    of the points on the sphere's surface.
    """
    # Start with the 12 vertices of a base icosahedron
    # Golden ratio
    t = (1.0 + np.sqrt(5.0)) / 2.0
    
    vertices = [
        [-1,  t,  0], [ 1,  t,  0], [-1, -t,  0], [ 1, -t,  0],
        [ 0, -1,  t], [ 0,  1,  t], [ 0, -1, -t], [ 0,  1, -t],
        [ t,  0, -1], [ t,  0,  1], [-t,  0, -1], [-t,  0,  1]
    ]
    vertices = np.array(vertices, dtype=float)
    # Normalize the vertices to form a unit sphere
    vertices /= np.linalg.norm(vertices, axis=1)[:, np.newaxis]

    # Define the 20 triangular faces of the icosahedron by vertex indices
    faces = [
        [0, 11, 5], [0, 5, 1], [0, 1, 7], [0, 7, 10], [0, 10, 11],
        [1, 5, 9], [5, 11, 4], [11, 10, 2], [10, 7, 6], [7, 1, 8],
        [3, 9, 4], [3, 4, 2], [3, 2, 6], [3, 6, 8], [3, 8, 9],
        [4, 9, 5], [2, 4, 11], [6, 2, 10], [8, 6, 7], [9, 8, 1]
    ]
    faces = np.array(faces, dtype=int)

    # Recursively subdivide the faces
    for _ in range(subdivisions):
        new_faces = []
        midpoint_cache = {}
        
        for face in faces:
            v1_idx, v2_idx, v3_idx = face
            
            # Function to get or create a midpoint
            def get_midpoint(idx1, idx2):
                nonlocal vertices
                key = tuple(sorted((idx1, idx2)))
                if key in midpoint_cache:
                    return midpoint_cache[key]
                
                # Calculate the midpoint
                mid = (vertices[idx1] + vertices[idx2]) / 2.0
                # Project the midpoint onto the unit sphere
                mid /= np.linalg.norm(mid)
                
                # Add the new vertex and get its index
                mid_idx = len(vertices)
                vertices = np.vstack([vertices, mid])
                midpoint_cache[key] = mid_idx
                return mid_idx

            # Get midpoints of the edges of the face
            m12 = get_midpoint(v1_idx, v2_idx)
            m23 = get_midpoint(v2_idx, v3_idx)
            m31 = get_midpoint(v3_idx, v1_idx)
            
            # Create 4 new faces
            new_faces.extend([
                [v1_idx, m12, m31],
                [v2_idx, m23, m12],
                [v3_idx, m31, m23],
                [m12, m23, m31]
            ])
        faces = np.array(new_faces)

    # The vertices array now contains all the points.
    # Scale to the desired radius.
    return vertices * radius


def sample_sphere(N: int, R: float = 1.0, noise_param: float = 0.0) -> np.ndarray:
    """
    Samples N points uniformly from a sphere of given radius.

    Args:
        N: The number of points to sample.
        R: (Optional) The radius of the sphere. Default is 1.0.
        noise_param: (Optional) Standard deviation of Gaussian noise to add.
                     Default is 0.0 (no noise). This is analogous to the
                     noise_param in klein_bottle_imm.m.

    Returns:
        A 3xN NumPy array where each column is a 3D coordinate [x; y; z]
        of a sampled point on the sphere surface (potentially with noise).

    Method: Points are generated by sampling 3D Gaussian random vectors
    and normalizing them, which ensures a uniform distribution on the
    sphere's surface. This approach is widely used for uniform sphere sampling.

    Reference: The function signature (input N, output X) and the optional
    noise parameter are designed to be analogous to 'klein_bottle_imm.m'
    from the PH-roadmap repository.
    URL: https://github.com/n-otter/PH-roadmap/blob/master/matlab/synthetic_data_sets_scripts/klein_bottle_imm.m
    """
    if N <= 0:
        raise ValueError("N (number of points) must be a positive integer.")

    # --- Sphere Sampling Logic ---
    points_raw = np.random.randn(3, N)
    norms = np.linalg.norm(points_raw, axis=0)
    X = R * (points_raw / norms)

    # --- Add Noise (optional, analogous to klein_bottle_imm.m) ---
    if noise_param > 0:
        X = X + noise_param * np.random.randn(*X.shape)

    return X